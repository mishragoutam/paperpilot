import React, { useState, useRef, useEffect } from 'react';
import { useAppStore } from '../../store/useAppStore';

export const Header: React.FC = () => {
  const {
    currentView,
    setCurrentView,
    toggleLeftPanel,
    toggleRightPanel,
    toggleTheme,
    theme,
    db,
    activeDocumentId,
    triggerUndo,
    triggerRedo,
    activeProjectId,
    leftPanelOpen,
    rightPanelOpen,
  } = useAppStore();

  const [exportOpen, setExportOpen] = useState(false);
  const exportRef = useRef<HTMLDivElement>(null);

  const activeDoc = db.documents.find(d => d.id === activeDocumentId);
  const wordCount = activeDoc ? activeDoc.wordCount : 0;

  useEffect(() => {
    const handleClickOutside = (e: MouseEvent) => {
      if (exportRef.current && !exportRef.current.contains(e.target as Node)) {
        setExportOpen(false);
      }
    };
    document.addEventListener('mousedown', handleClickOutside);
    return () => document.removeEventListener('mousedown', handleClickOutside);
  }, []);

  const handleExport = (format: 'md' | 'html' | 'txt' | 'tex') => {
    if (!activeDoc) return;
    let content = activeDoc.content;
    let mime = 'text/plain';
    let ext = 'txt';
    if (format === 'html') { mime = 'text/html'; ext = 'html'; }
    else if (format === 'md') {
      content = content
        .replace(/<h1>(.*?)<\/h1>/gi, '# $1\n\n')
        .replace(/<h2>(.*?)<\/h2>/gi, '## $1\n\n')
        .replace(/<h3>(.*?)<\/h3>/gi, '### $1\n\n')
        .replace(/<strong>(.*?)<\/strong>/gi, '**$1**')
        .replace(/<em>(.*?)<\/em>/gi, '*$1*')
        .replace(/<p>(.*?)<\/p>/gi, '$1\n\n')
        .replace(/<[^>]+>/g, '');
      mime = 'text/markdown'; ext = 'md';
    } else if (format === 'tex') {
      const plain = activeDoc.content.replace(/<[^>]+>/g, ' ');
      content = `% Generated by PaperPilot\n\\documentclass{article}\n\\begin{document}\n\\title{${activeDoc.title}}\n\\maketitle\n${plain}\n\\end{document}`;
      mime = 'application/x-tex'; ext = 'tex';
    } else if (format === 'txt') {
      content = content.replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim();
    }
    const blob = new Blob([content], { type: mime });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${activeDoc.title.replace(/\.[^/.]+$/, '')}.${ext}`;
    a.click();
    URL.revokeObjectURL(url);
    setExportOpen(false);
  };

  const navItems = [
    { key: 'workspace', label: 'Workspace', icon: 'edit_document' },
    { key: 'library', label: 'Library', icon: 'folder_copy' },
    { key: 'originality', label: 'Originality', icon: 'verified' },
    { key: 'settings', label: 'Settings', icon: 'tune' },
  ] as const;

  return (
    <header className="fixed top-0 left-0 right-0 z-50 h-14 bg-surface-container-lowest border-b border-surface-container flex items-center px-4 gap-3 select-none shadow-sm">
      {/* Brand */}
      <button
        onClick={() => setCurrentView('workspace')}
        className="flex items-center gap-2 shrink-0 hover:opacity-80 transition-opacity"
      >
        <div className="w-7 h-7 rounded-lg bg-gradient-to-br from-indigo-600 to-indigo-500 flex items-center justify-center shadow-sm">
          <span className="text-white font-bold text-sm">P</span>
        </div>
        <span className="font-semibold text-sm text-on-surface tracking-tight hidden sm:block">PaperPilot</span>
      </button>

      <div className="w-px h-5 bg-outline-variant shrink-0" />

      {/* Navigation tabs */}
      <nav className="flex items-center gap-0.5">
        {navItems.map(item => (
          <button
            key={item.key}
            onClick={() => setCurrentView(item.key)}
            className={`flex items-center gap-1.5 px-3 py-1.5 rounded-md text-xs font-medium transition-all ${
              currentView === item.key
                ? 'bg-primary/10 text-primary'
                : 'text-on-surface-variant hover:bg-surface-container hover:text-on-surface'
            }`}
          >
            <span className="material-symbols-outlined text-[15px]">{item.icon}</span>
            <span className="hidden lg:block">{item.label}</span>
          </button>
        ))}
      </nav>

      {/* Active document pill */}
      {currentView === 'workspace' && activeDoc && (
        <div className="hidden md:flex items-center gap-1.5 px-2.5 py-1 rounded-md bg-surface-container border border-outline-variant max-w-xs min-w-0">
          <span className="material-symbols-outlined text-outline text-[13px] shrink-0">description</span>
          <span className="text-xs text-on-surface truncate font-mono">{activeDoc.title}</span>
          {wordCount > 0 && (
            <span className="text-[10px] text-outline shrink-0">{wordCount.toLocaleString()}w</span>
          )}
        </div>
      )}

      <div className="flex-1" />

      {/* Undo / Redo (workspace only) */}
      {currentView === 'workspace' && (
        <div className="hidden xl:flex items-center gap-0.5">
          <button onClick={triggerUndo} className="w-7 h-7 flex items-center justify-center rounded hover:bg-surface-container text-on-surface-variant hover:text-on-surface transition-colors" title="Undo (Ctrl+Z)">
            <span className="material-symbols-outlined text-[15px]">undo</span>
          </button>
          <button onClick={triggerRedo} className="w-7 h-7 flex items-center justify-center rounded hover:bg-surface-container text-on-surface-variant hover:text-on-surface transition-colors" title="Redo (Ctrl+Y)">
            <span className="material-symbols-outlined text-[15px]">redo</span>
          </button>
          <div className="w-px h-4 bg-outline-variant mx-1" />
        </div>
      )}

      {/* Panel toggles (workspace only) */}
      {currentView === 'workspace' && (
        <>
          <button
            onClick={toggleLeftPanel}
            className={`w-7 h-7 flex items-center justify-center rounded transition-colors ${leftPanelOpen ? 'bg-primary/10 text-primary' : 'hover:bg-surface-container text-on-surface-variant hover:text-on-surface'}`}
            title="Toggle Research Panel"
          >
            <span className="material-symbols-outlined text-[15px]">dock_to_left</span>
          </button>
          <button
            onClick={toggleRightPanel}
            className={`w-7 h-7 flex items-center justify-center rounded transition-colors ${rightPanelOpen ? 'bg-primary/10 text-primary' : 'hover:bg-surface-container text-on-surface-variant hover:text-on-surface'}`}
            title="Toggle AI Assistant"
          >
            <span className="material-symbols-outlined text-[15px]">dock_to_right</span>
          </button>
          <div className="w-px h-4 bg-outline-variant" />
        </>
      )}

      {/* Export button */}
      {currentView === 'workspace' && (
        <div className="relative" ref={exportRef}>
          <button
            onClick={() => setExportOpen(!exportOpen)}
            className="flex items-center gap-1 px-2.5 py-1.5 rounded-md bg-primary text-white text-xs font-medium hover:bg-primary-container transition-colors shadow-sm"
          >
            <span className="material-symbols-outlined text-[14px]">file_download</span>
            <span>Export</span>
            <span className={`material-symbols-outlined text-[12px] transition-transform ${exportOpen ? 'rotate-180' : ''}`}>expand_more</span>
          </button>
          {exportOpen && (
            <div className="absolute right-0 top-full mt-1 w-48 bg-surface-container-lowest rounded-lg shadow-lg border border-surface-container py-1 z-50 animate-scale-in">
              {[
                { fmt: 'md' as const, icon: 'markdown', label: 'Markdown (.md)' },
                { fmt: 'tex' as const, icon: 'functions', label: 'LaTeX (.tex)' },
                { fmt: 'html' as const, icon: 'html', label: 'HTML (.html)' },
                { fmt: 'txt' as const, icon: 'description', label: 'Plain Text (.txt)' },
              ].map(({ fmt, icon, label }) => (
                <button
                  key={fmt}
                  onClick={() => handleExport(fmt)}
                  className="w-full text-left px-3 py-2 hover:bg-surface-container flex items-center gap-2 text-on-surface text-xs transition-colors"
                >
                  <span className="material-symbols-outlined text-[15px] text-primary">{icon}</span>
                  <span>{label}</span>
                </button>
              ))}
            </div>
          )}
        </div>
      )}

      {/* Theme toggle */}
      <button
        onClick={toggleTheme}
        className="w-7 h-7 flex items-center justify-center rounded hover:bg-surface-container text-on-surface-variant hover:text-on-surface transition-colors"
        title="Toggle Theme"
      >
        <span className="material-symbols-outlined text-[15px]">{theme === 'dark' ? 'light_mode' : 'dark_mode'}</span>
      </button>

      {/* Window controls */}
      <div className="flex items-center ml-1 shrink-0">
        <button onClick={() => (window as any).electronAPI?.minimize?.()} className="w-7 h-6 flex items-center justify-center text-on-surface-variant hover:bg-surface-container hover:text-on-surface transition-colors rounded" title="Minimize">
          <span className="material-symbols-outlined text-[14px]">minimize</span>
        </button>
        <button onClick={() => (window as any).electronAPI?.maximize?.()} className="w-7 h-6 flex items-center justify-center text-on-surface-variant hover:bg-surface-container hover:text-on-surface transition-colors rounded" title="Maximize">
          <span className="material-symbols-outlined text-[13px]">crop_square</span>
        </button>
        <button onClick={() => (window as any).electronAPI?.close?.()} className="w-7 h-6 flex items-center justify-center text-on-surface-variant hover:bg-red-500 hover:text-white transition-colors rounded" title="Close">
          <span className="material-symbols-outlined text-[14px]">close</span>
        </button>
      </div>
    </header>
  );
};
